ensure_new_output <- function(path) {
  if (file.exists(path) && !dir.exists(path)) stop("Output path is a file: ", path)
  if (dir.exists(path) && length(list.files(path, all.files = TRUE, no.. = TRUE)))
    stop("Output directory is not empty. Set a new RUN_ID: ", path, call. = FALSE)
}
