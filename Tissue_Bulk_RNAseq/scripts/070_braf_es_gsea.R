check_output_writing <- function() {
  probes <- character()
  on.exit(unlink(probes, force = TRUE), add = TRUE)
  probe_data <- data.frame(probe_id = c(1L, 2L), value = c(0.25, -0.5))
  for (d in c("", output_subdirs)) {
    probe_name <- paste0(".write_test_", strrep("x", 40L), ".csv")
    relative_probe <- if (nzchar(d)) file.path(d, probe_name) else probe_name
    p <- output_path(relative_probe)
    if (file.exists(p)) stopf("Refusing to overwrite an existing test file:\n", p)
    probes <- c(probes, p)
    write_csv(probe_data, relative_probe)
    recovered <- tryCatch(
      data.table::fread(p, data.table = FALSE, showProgress = FALSE),
      error = function(e) stopf("Cannot read back output test:\n", p,
                                "\n", conditionMessage(e))
    )
    if (!identical(names(recovered), names(probe_data)) ||
        nrow(recovered) != nrow(probe_data) ||
        !isTRUE(all.equal(as.numeric(recovered$value), probe_data$value))) {
      stopf("Output write/read validation failed:\n", p)
    }
  }
  message("PASS: output subfolders created and CSV write/read checks completed.")
  invisible(TRUE)
}
