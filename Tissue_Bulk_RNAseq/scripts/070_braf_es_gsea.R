    ty <- legend_bottom + (v + colour_limit) / (2 * colour_limit) * legend_height
    grid::grid.lines(c(legend_x + 0.0075, legend_x + 0.011), c(ty, ty),
                     gp = grid::gpar(lwd = 0.5))
    text(format(v, trim = TRUE), legend_x + 0.016, ty, 8.0, just = "left")
  }
  n_h <- unique(hallmark_results$n_tests_in_family)
  hall_scope <- if (length(n_h) == 1L) paste0(n_h, " Hallmark pathways per comparison") else
    "eligible Hallmark pathways per comparison (see tables)"
