    record_input(paths[i], paste0("DE_", comp$key))
    de <- standardise_de(paths[i], comp)
    source_qc[[i]] <- de$qc
    write_csv(de$data, paste0("tables/", comp$key, "_standardised_DE.csv"))
    rh <- make_ranks(de$data, "HALLMARK", comp$key)
    rg <- make_ranks(de$data, "CUSTOM", comp$key)
    rank_qc[[i]] <- rbind(rh$qc, rg$qc)
    signature_qc[[i]] <- rbind(rh$signature_qc, rg$signature_qc)
    write_csv(rh$table, paste0("tables/ranked/", comp$key, "_Hallmark.csv"))
    write_csv(rg$table, paste0("tables/ranked/", comp$key, "_Gastric.csv"))
    hs[[i]] <- run_enrichment(rh, "HALLMARK", comp)
    gs[[i]] <- run_enrichment(rg, "CUSTOM", comp)
  }
  hallmark_results <- do.call(rbind, hs)
  gastric_results <- do.call(rbind, gs)
  write_csv(do.call(rbind, rank_qc), "qc/RANKING_METADATA.csv")
  write_csv(do.call(rbind, source_qc), "qc/DE_IMPORT_COLUMNS.csv")
  write_csv(do.call(rbind, signature_qc), "qc/GASTRIC_GENE_RETENTION.csv")
}
