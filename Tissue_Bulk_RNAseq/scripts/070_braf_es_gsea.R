first_existing <- function(paths) {
  paths <- unique(paths[!is.na(paths) & nzchar(paths)])
  found <- paths[file.exists(paths)]
  if (!length(found)) return(NA_character_)
  normalizePath(found[1], winslash = "/", mustWork = TRUE)
}
