standardise_de <- function(path, comp) {
  raw <- read_tab(path)

  gene_col <- find_col(raw, c("SYMBOL", "gene_symbol", "GeneSymbol", "Gene",
                              "genes", "external_gene_name", "gene_name"))
  fc_col <- find_col(raw, c("logFC", "log2FoldChange", "log2FC"))
  cpm_col <- find_col(raw, c("logCPM", "log2CPM", "mean_logCPM", "AveExpr"))
  lr_col <- find_col(raw, c("LR", "LRT", "likelihood_ratio"), FALSE)
  p_col <- find_col(raw, c("PValue", "P.Value", "pvalue", "p_val", "pval"), FALSE)
  fdr_col <- find_col(raw, c("FDR", "padj", "adj.P.Val", "qvalue"), FALSE)
  pull_num <- function(column) {
    if (is.na(column)) rep(NA_real_, nrow(raw)) else as_number(raw[[column]], column)
  }
  if (de_source == "archived_standardized_DE") {
    required <- c("source_file", "comparison_id", "comparison", "original_row")
    if (!all(required %in% names(raw))) stopf("Unrecognised archived DE format: ", path)
    if (!all(raw$source_file == comp$file) || !all(raw$comparison_id == comp$archived_id) ||
        !all(raw$comparison == comp$original_comparison)) stopf(
          "Archived DE provenance does not match the expected contrast: ", path)
  }
  original_row <- if ("original_row" %in% names(raw)) {
    as_number(raw$original_row, "original_row")
  } else seq_len(nrow(raw))
  if (anyNA(original_row) || anyDuplicated(original_row)) stopf("Invalid original_row: ", path)
  d <- data.frame(original_row = original_row, Gene = clean_symbols(raw[[gene_col]]),
    logFC = pull_num(fc_col) * comp$logFC_multiplier, logCPM = pull_num(cpm_col),
    LR = pull_num(lr_col), PValue = pull_num(p_col), FDR = pull_num(fdr_col))

  all_input_symbols <- d$Gene
  valid <- !is.na(d$Gene) & is.finite(d$logFC)
  qc <- data.frame(key = comp$key, input_file = path, input_rows = nrow(d),
    rows_removed_missing_symbol_or_nonfinite_FC = sum(!valid),
    input_rows_nonfinite_logCPM = sum(!is.finite(d$logCPM)),
    gene_column = gene_col,
    logFC_column = fc_col, logCPM_column = cpm_col, LR_column = lr_col,
    PValue_column = p_col, FDR_column = fdr_col)
  d <- d[valid, , drop = FALSE]
  if (!nrow(d)) stopf("No valid genes: ", path)
  if (mean(grepl("^ENSG[0-9]+", d$Gene)) > 0.5 ||
      mean(grepl("^[0-9]+$", d$Gene)) > 0.5) stopf(
        "Gene column appears to contain IDs rather than symbols: ", gene_col)
  attr(d, "all_input_symbols") <- all_input_symbols
  list(data = d, qc = qc)
}
make_ranks <- function(d, family, key) {
  if (!family %in% c("HALLMARK", "CUSTOM")) stopf("Unknown family: ", family)
  apply_logcpm_filter <- identical(family, "HALLMARK")
  filter_mode <- if (apply_logcpm_filter) paste0("LOGCPM_GE_", logcpm_cutoff) else
    gastric_filter_mode

  expression_table <- if (apply_logcpm_filter) {
    d[is.finite(d$logCPM) & d$logCPM >= logcpm_cutoff, , drop = FALSE]
  } else {
    d
  }
  if (nrow(expression_table) < 100L) stopf("Too few genes: ", key, " / ", family)

  safe_optional_probability <- function(x, label) {
    if (any(is.finite(x) & (x < 0 | x > 1))) stopf(
      "Out-of-range ", label, " in ", key)
    ok <- is.finite(x) & x >= 0 & x <= 1
    out <- rep(NA_real_, length(x))
    if (any(ok)) out[ok] <- probability_safe(x[ok], label)
    out
  }
  expression_table$PValue_safe <- safe_optional_probability(
    expression_table$PValue, "gene-level PValue")
  if (family == "HALLMARK" && sum(is.finite(expression_table$LR)) >= 100L) {
    if (any(is.finite(expression_table$LR) & expression_table$LR < 0)) stopf(
      "Negative LR in ", key)
    expression_table$rank_metric <- sign(expression_table$logFC) * sqrt(expression_table$LR)
    metric <- "sign(logFC) * sqrt(LR)"
  } else if (family == "CUSTOM" && any(is.finite(expression_table$FDR))) {
    expression_table$FDR_safe <- safe_optional_probability(
      expression_table$FDR, "gene-level FDR")
    expression_table$rank_metric <- sign(expression_table$logFC) *
      -log10(expression_table$FDR_safe)
    metric <- "sign(logFC) * -log10(gene-level FDR)"
  } else {
    expression_table$rank_metric <- sign(expression_table$logFC) *
      -log10(expression_table$PValue_safe)
    metric <- "sign(logFC) * -log10(PValue)"
    warning("Using the existing nominal-P fallback for ", family, " / ", key,
            call. = FALSE)
  }
  f <- expression_table[is.finite(expression_table$rank_metric), , drop = FALSE]
  n_invalid_rank <- nrow(expression_table) - nrow(f)
  if (n_invalid_rank > 0L) warning(
    key, " / ", family, ": excluded ", n_invalid_rank,
    " rows without a finite required ranking statistic. See QC; no P-value imputation.",
    call. = FALSE)
  if (nrow(f) < 100L) stopf("Too few valid ranking statistics: ", key, " / ", family)

  f <- f[order(f$Gene, -abs(f$rank_metric), f$PValue_safe,
               -abs(f$logFC), f$original_row, na.last = TRUE, method = "radix"), , drop = FALSE]
  r <- f[!duplicated(f$Gene), , drop = FALSE]
  r <- r[order(-r$rank_metric, r$Gene, method = "radix"), , drop = FALSE]
  r$rank_before_tiebreak <- r$rank_metric
  tied <- anyDuplicated(r$rank_metric) > 0L
  if (tied) r$rank_metric <- r$rank_metric - seq_len(nrow(r)) * 1e-12
  r <- r[order(-r$rank_metric, method = "radix"), , drop = FALSE]
  ranks <- setNames(r$rank_metric, r$Gene)
  stopifnot(!anyDuplicated(names(ranks)), all(is.finite(ranks)), all(diff(ranks) <= 0))
  if (!any(r$rank_before_tiebreak != 0)) stopf(
    "All original ranking statistics are zero: ", key, " / ", family)

  input_symbols <- attr(d, "all_input_symbols")
  if (is.null(input_symbols)) input_symbols <- d$Gene
  sq <- data.frame(key = key, family = family, filter_mode = filter_mode,
    Gene = gastric_genes,
    present_in_input_DE = gastric_genes %in% input_symbols,
    present_before_expression_filter = gastric_genes %in% d$Gene,
    present_after_expression_filter = gastric_genes %in% expression_table$Gene,
    present_with_valid_rank_statistic = gastric_genes %in% f$Gene,
    present_in_ranked_list = gastric_genes %in% names(ranks))
  sq$status <- ifelse(!sq$present_in_input_DE, "absent_from_input_DE",
    ifelse(!sq$present_before_expression_filter, "no_valid_logFC",
    ifelse(!sq$present_after_expression_filter, "removed_by_Hallmark_logCPM_filter",
    ifelse(!sq$present_with_valid_rank_statistic, "no_valid_ranking_statistic", "retained"))))
  if (!apply_logcpm_filter) stopifnot(
    nrow(expression_table) == nrow(d),
    identical(sq$present_before_expression_filter, sq$present_after_expression_filter))

  overlap <- intersect(gastric_genes, names(ranks))
  if (family == "CUSTOM" && length(overlap) < length(gastric_genes)) warning(
    key, ": gastric coverage is ", length(overlap), "/", length(gastric_genes),
    " without a logCPM filter. Missing/unrankable: ",
    paste(setdiff(gastric_genes, names(ranks)), collapse = ", "),
    ". Missing genes are reported, not fabricated.", call. = FALSE)
  list(ranks = ranks, table = r, metric = metric, filter_mode = filter_mode,
    qc = data.frame(key = key, family = family, filter_mode = filter_mode,
      logCPM_filter_applied = apply_logcpm_filter,
      rank_metric = metric, input_valid_rows = nrow(d),
      rows_after_expression_filter = nrow(expression_table),
      rows_removed_by_logCPM_filter = nrow(d) - nrow(expression_table),
      rows_removed_invalid_rank = n_invalid_rank,
      ranked_symbols = length(ranks), duplicate_rows_removed = nrow(f) - nrow(r),
      tied_rows_before_perturbation = sum(duplicated(r$rank_before_tiebreak)),
      zero_ranks_before_perturbation = sum(r$rank_before_tiebreak == 0),
      tie_perturbation_applied = tied,
      ranked_genes_below_logCPM_cutoff = sum(is.finite(r$logCPM) & r$logCPM < logcpm_cutoff),
      ranked_genes_nonfinite_logCPM = sum(!is.finite(r$logCPM)),
      signature_overlap = length(overlap)),
    signature_qc = sq)
}

filter_logic_tests <- function() {
  genes <- c(gastric_genes, sprintf("TEST_BACKGROUND_%03d", seq_len(106L)))
  n <- length(genes)
  d <- data.frame(original_row = seq_len(n), Gene = genes,
    logFC = rep(c(-1, 1), length.out = n), logCPM = rep(3, n),
    LR = seq(1, 8, length.out = n), PValue = seq(0.0001, 0.9, length.out = n),
    FDR = seq(0.001, 1, length.out = n))
  d$logCPM[1:4] <- c(1, -3, NA_real_, Inf)
  h <- make_ranks(d, "HALLMARK", "SYNTHETIC_FILTER_TEST")
  g <- make_ranks(d, "CUSTOM", "SYNTHETIC_FILTER_TEST")
  stopifnot(!any(genes[1:4] %in% names(h$ranks)),
    all(genes %in% names(g$ranks)), length(g$ranks) == n,
    length(g$ranks) > length(gastric_genes),
    g$qc$rows_removed_by_logCPM_filter == 0L,
    h$qc$rows_removed_by_logCPM_filter == 4L,
    g$qc$signature_overlap == 24L,
    identical(g$filter_mode, "ALL_VALID_GENES_NO_LOGCPM"))

  d$FDR[5] <- NA_real_
  g_na <- suppressWarnings(make_ranks(d, "CUSTOM", "SYNTHETIC_NA_TEST"))
  stopifnot(!genes[5] %in% names(g_na$ranks),
    g_na$qc$rows_removed_invalid_rank == 1L,
    genes[5] %in% g_na$signature_qc$Gene[g_na$signature_qc$status == "no_valid_ranking_statistic"])

  d$FDR[5] <- 0
  duplicate <- d[6, , drop = FALSE]
  duplicate$original_row <- n + 1L
  duplicate$FDR <- 1e-7
  g_dup <- make_ranks(rbind(d, duplicate), "CUSTOM", "SYNTHETIC_DUPLICATE_TEST")
  stopifnot(length(g_dup$ranks) == n, !anyDuplicated(names(g_dup$ranks)),
    all(is.finite(g_dup$ranks)))
  message("PASS: synthetic tests of Hallmark-only filtering, unfiltered gastric background, missing statistics and duplicates.")
  invisible(TRUE)
}

run_enrichment <- function(obj, family, comp) {
  is_h <- family == "HALLMARK"
  pathways <- if (is_h) hallmark_sets else setNames(list(gastric_genes), gastric_pathway)
  min_size <- if (is_h) hallmark_min_size else custom_min_size
  max_size <- if (is_h) hallmark_max_size else min(custom_max_size, length(obj$ranks) - 1L)
  overlaps <- vapply(pathways, function(g) sum(g %in% names(obj$ranks)), integer(1))
  eligible <- overlaps >= min_size & overlaps <= max_size
  write_csv(data.frame(key = comp$key, family = family, pathway = names(pathways),
    database_size = lengths(pathways), overlap = overlaps, eligible = eligible),
    paste0("qc/", comp$key, "_", family, "_pathway_overlap.csv"))
  if (!any(eligible)) stopf("No eligible gene sets for ", comp$key, " / ", family)

  set.seed(seed)
  fg <- fgsea::fgseaMultilevel(pathways = pathways[eligible], stats = obj$ranks,
    minSize = min_size, maxSize = max_size, scoreType = "std", gseaParam = 1,
    eps = if (is_h) hallmark_eps else custom_eps,
    nPermSimple = if (is_h) hallmark_nperm_simple else custom_nperm_simple,
    sampleSize = fgsea_sample_size, nproc = fgsea_workers)
  fg <- as.data.frame(fg)
  if (nrow(fg) != sum(eligible)) stopf("Unexpected number of GSEA results.")
  fg$fgsea_reported_padj <- fg$padj
  fg$padj <- stats::p.adjust(fg$pval, method = "BH")
  if (!isTRUE(all.equal(fg$fgsea_reported_padj, fg$padj, tolerance = 1e-12))) {
    warning("Recomputed BH values differ from fgsea's padj; inspect outputs.", call. = FALSE)
  }
  if (is.list(fg$leadingEdge)) fg$leadingEdge <- vapply(
    fg$leadingEdge, paste, collapse = ";", FUN.VALUE = character(1))
  fg$key <- comp$key
  fg$comparison_label <- comp$label
  fg$family <- family
  fg$rank_metric <- obj$metric
  fg$filter_mode <- obj$filter_mode
  if (!is_h) stopifnot(identical(fg$filter_mode, gastric_filter_mode))
  fg$n_tests_in_family <- nrow(fg)
  fg$fdr_scope <- if (is_h) "BH across eligible Hallmarks within this comparison" else
    "Single custom gene set within this comparison: padj = nominal P"
  fg$n_signature_total <- if (is_h) NA_integer_ else length(gastric_genes)
  fg$n_signature_overlap <- if (is_h) NA_integer_ else sum(gastric_genes %in% names(obj$ranks))
  fg
}

read_saved <- function(path, family) {
  record_input(path, paste0("saved_", family, "_results"))
  d <- read_tab(path)
  required <- c("comparison_id", "comparison", "pathway", "pval", "padj", "ES", "NES", "size", "filter_mode")
  if (!all(required %in% names(d))) stopf("Unrecognised saved result format: ", path)
  if (!all(d$filter_mode == "LOGCPM_GE_2") || logcpm_cutoff != 2) stopf("Saved filter mismatch.")
  idx <- match(d$comparison_id, comparisons$archived_id)
  if (anyNA(idx) || !all(d$comparison == comparisons$original_comparison[idx])) {
    stopf("Saved contrasts do not match the five-table added-DE analysis: ", path)
  }
  if (anyDuplicated(paste(d$comparison_id, d$pathway))) stopf("Duplicate saved results.")
  if (family == "HALLMARK") {
    for (cid in comparisons$archived_id) {
      ix <- which(d$comparison_id == cid)
      if (length(ix) != 50L || !setequal(d$pathway[ix], names(hallmark_sets))) {
        stopf("Saved Hallmark collection is incomplete for ", cid)
      }
      if (!isTRUE(all.equal(d$padj[ix], p.adjust(d$pval[ix], "BH"), tolerance = 1e-10))) {
        stopf("Saved Hallmark BH check failed for ", cid)
      }
    }
  } else {
    if (nrow(d) != 5L || !all(d$pathway == gastric_pathway) ||
        !isTRUE(all.equal(d$padj, d$pval, tolerance = 1e-12))) stopf("Saved gastric scope mismatch.")
    if (!all(d$n_signature_genes_total == 24L)) stopf("Saved gastric signature is not 24 genes.")
  }
  d$key <- comparisons$key[idx]
  d$comparison_label <- comparisons$label[idx]
  d$family <- family
  d$rank_metric <- if (family == "HALLMARK") "sign(logFC) * sqrt(LR)" else
    "sign(logFC) * -log10(gene-level FDR)"
  d$n_tests_in_family <- if (family == "HALLMARK") 50L else 1L
  d$n_signature_total <- if (family == "HALLMARK") NA_integer_ else d$n_signature_genes_total
  d$n_signature_overlap <- if (family == "HALLMARK") NA_integer_ else d$n_signature_genes_overlap_ranked
  d
}
