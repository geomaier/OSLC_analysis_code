nes_colour <- function(x) {
  ans <- rep("#E6E6E6", length(x)); ok <- is.finite(x)
  idx <- round((x[ok] / colour_limit + 1) * 500) + 1L
  ans[ok] <- palette[pmax(1L, pmin(1001L, idx))]
  ans
}
contrast_text_colour <- function(colour) {
  rgb <- grDevices::col2rgb(colour) / 255
  linear <- ifelse(rgb <= 0.04045, rgb / 12.92, ((rgb + 0.055) / 1.055)^2.4)
  lum <- as.numeric(c(0.2126, 0.7152, 0.0722) %*% linear)
  ifelse((lum + 0.05) / 0.05 >= 1.05 / (lum + 0.05), "black", "white")
}
