need_file <- function(path) {
  if (!file.exists(path)) stopf("File not found:\n", path)
  normalizePath(path, winslash = "/", mustWork = TRUE)
}
script_location <- function() {
  frames <- sys.frames()
  for (i in rev(seq_along(frames))) {
    f <- frames[[i]]$ofile
    if (!is.null(f) && file.exists(f)) return(dirname(normalizePath(f)))
  }
  args <- grep("^--file=", commandArgs(), value = TRUE)
  if (length(args)) return(dirname(normalizePath(sub("^--file=", "", args[1]))))
  getwd()
}
