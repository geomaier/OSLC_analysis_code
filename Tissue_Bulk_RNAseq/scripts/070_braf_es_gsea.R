read_tab <- function(path) {

  d <- data.table::fread(need_file(path), data.table = FALSE, check.names = FALSE,
                         fill = FALSE, na.strings = c("NA", "NaN", ""))
  if (ncol(d) < 2L || !nrow(d)) stopf("Empty or incorrectly parsed table: ", path)
  if (anyDuplicated(names(d))) stopf("Duplicate column names in ", path)
  d
}

output_path <- function(relative_path) {
  if (length(relative_path) != 1L || is.na(relative_path) || !nzchar(relative_path)) {
    stopf("Output filename must be one non-empty relative path.")
  }
  p <- file.path(out_dir, relative_path)

  if (.Platform$OS.type == "windows" && nchar(p, type = "chars") >= 240L) {
    stopf("Output path is too long for this script's safe-path policy (",
          nchar(p, type = "chars"), " characters):\n", p,
          "\nThe default new subfolder keeps output paths short within the original folder.",
          "\nNo output has been redirected. Check whether base_dir or the run-folder name was changed.")
  }
  parent <- dirname(p)
  if (!dir.exists(parent)) {
    dir.create(parent, recursive = TRUE, showWarnings = FALSE)
  }
  if (!dir.exists(parent)) {
    stopf("Cannot create output subfolder:\n", parent,
          "\nCheck access to the original analysis folder. Outputs will not be redirected.")
  }
  p
}
write_csv <- function(x, relative_path) {
  p <- output_path(relative_path)
  tryCatch(
    data.table::fwrite(x, p, na = "NA"),
    error = function(e) stopf(
      "Cannot write output CSV:\n", p,
      "\nPath length: ", nchar(p, type = "chars"), " characters.",
      "\nParent directory exists: ", dir.exists(dirname(p)),
      "\nOriginal error: ", conditionMessage(e),
      "\nCheck output-folder access, available disk space and whether the file is open.")
  )
  invisible(p)
}
write_text <- function(x, relative_path) {
  p <- output_path(relative_path)
  tryCatch(
    writeLines(x, p, useBytes = TRUE),
    error = function(e) stopf(
      "Cannot write output text:\n", p,
      "\nPath length: ", nchar(p, type = "chars"), " characters.",
      "\nOriginal error: ", conditionMessage(e))
  )
  invisible(p)
}
find_col <- function(d, candidates, required = TRUE) {
  for (candidate in candidates) {
    hit <- which(tolower(names(d)) == tolower(candidate))
    if (length(hit)) return(names(d)[hit[1]])
  }
  if (required) stopf("Missing column: ", paste(candidates, collapse = " / "),
                      ". Found: ", paste(names(d), collapse = ", "))
  NA_character_
}
clean_symbols <- function(x) {
  x <- toupper(trimws(as.character(x)))
  x[x %in% c("", "NA", "NAN")] <- NA_character_
  x
}
as_number <- function(x, label) {
  s <- trimws(as.character(x))
  v <- suppressWarnings(as.numeric(s))
  bad <- !is.na(x) & nzchar(s) & !s %in% c("NA", "NaN") & is.na(v)
  if (any(bad)) stopf("Non-numeric values in ", label, ": ",
                      paste(head(unique(s[bad]), 4), collapse = ", "))
  v
}
probability_safe <- function(x, label) {
  if (any(!is.finite(x) | x < 0 | x > 1)) stopf(
    "Missing/invalid ", label, " in retained genes. These must not be converted ",
    "to very small P values. Check the input DE table.")
  floor_value <- if (any(x > 0)) min(x[x > 0]) * 0.1 else 1e-301
  if (!is.finite(floor_value) || floor_value <= 0) stopf("P-value floor underflow: ", label)
  x[x == 0] <- floor_value
  x
}
stars <- function(p) {
  ans <- rep("", length(p))
  ans[is.finite(p) & p < 0.05] <- "*"
  ans[is.finite(p) & p < 0.01] <- "**"
  ans[is.finite(p) & p < 0.001] <- "***"
  ans
}
format_probability <- function(p) {
  vapply(p, function(z) {
    if (!is.finite(z)) return("NA")
    if (z == 0) return("0 (check precision)")
    if (z < 0.001) return(sub("e([+-])0+", "e\\1", sprintf("%.2e", z)))
    if (z < 0.1) return(sprintf("%.4f", z))
    sprintf("%.3f", z)
  }, character(1))
}

