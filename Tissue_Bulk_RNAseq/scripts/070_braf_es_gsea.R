               "TNF-\u03b1 signalling\nvia NF-\u03baB",
               "Serrated Lesion\nGastric Metaplasia\nGene Signature")
  for (j in seq_along(x)) text(headers[j], x[j], 0.857, 9.4)
  first <- list(expression(italic(BRAF)~"V600E vs WT"),
                expression(italic(BRAF)~"V600E vs WT"),
                "ES+ vs ES\u2212 within", "ES+ vs ES\u2212 within",
                expression(italic(BRAF)~"V600E/ES+ vs"))
  second <- list("within ES\u2212", "within ES+", expression(italic(BRAF)~"V600E"),
                 expression(italic(BRAF)~"WT"), expression(italic(BRAF)~"WT/ES\u2212"))
  for (i in seq_along(y)) {
    text(first[[i]], 0.324, y[i] + 0.015, 10.0, just = "right")
    text(second[[i]], 0.324, y[i] - 0.016, 10.0, just = "right")
  }
  for (k in seq_len(nrow(plot_data))) {
    d <- plot_data[k, ]
    grid::grid.rect(x[d$column_order], y[d$row_order], width = 0.136, height = 0.098,
      gp = grid::gpar(fill = d$fill_colour, col = "white", lwd = 0.6))
    offset <- if (show_cell_p_values) 0.013 else 0
    text(d$upper_label, x[d$column_order], y[d$row_order] + offset,
         12.0, d$text_colour, "bold")
    if (show_cell_p_values) text(d$lower_label, x[d$column_order],
                                y[d$row_order] - 0.023, 8.1, d$text_colour)
  }

  legend_x <- 0.951; legend_bottom <- 0.290; legend_height <- 0.402
