    grid::grid.text(label, x, y, just = just,
      gp = grid::gpar(fontfamily = font_family, fontsize = size,
                      col = colour, fontface = face, lineheight = 1.10))
  }
  if (show_main_title) text(figure_title, 0.018, 0.975, 13.5, face = "bold", just = "left")
